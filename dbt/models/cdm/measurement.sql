select
    row_number() over (order by event_id, concept_id)::integer  as measurement_id,
    person_id::integer                                      as person_id,
    concept_id::integer                                     as measurement_concept_id,
    start_datetime::date                                    as measurement_date,
    start_datetime                                          as measurement_datetime,
    null::text                                              as measurement_time,
    {{ var('type_ehr') }}::integer                          as measurement_type_concept_id,
    null::integer                                           as operator_concept_id,
    value_number::double precision                          as value_as_number,
    value_as_concept_id::integer                            as value_as_concept_id,
    unit_concept_id::integer                                as unit_concept_id,
    null::double precision                                  as range_low,
    null::double precision                                  as range_high,
    null::integer                                           as provider_id,
    visit_occurrence_id::integer                            as visit_occurrence_id,
    null::integer                                           as visit_detail_id,
    source_code                                             as measurement_source_value,
    source_concept_id::integer                              as measurement_source_concept_id,
    unit_code                                               as unit_source_value,
    null::integer                                           as unit_source_concept_id,
    value_source_value                                      as value_source_value,
    null::integer                                           as measurement_event_id,
    null::integer                                           as meas_event_field_concept_id
from {{ ref('int_events_mapped') }}
where domain_id = 'Measurement'
